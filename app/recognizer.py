from pathlib import Path
import cv2
import numpy as np
from PIL import Image, ImageDraw, ImageFont
from .constants import ALLOWED

try:
    import joblib
except Exception:
    joblib = None


class TemplateOCR:
    """Small offline OCR specialized for Russian plate glyphs.

    This is a competition-safe baseline with no external API/model files.
    It performs best on rectified plates and synthetic data generated by this
    repository. A neural OCR can be plugged in later with the same predict API.
    """
    def __init__(self, size=(32, 48)):
        self.tw, self.th = size
        self.templates = self._build_templates()
        self.svm = None
        model_path = Path('models/ocr_svm.joblib')
        if joblib is not None and model_path.exists():
            try:
                self.svm = joblib.load(model_path)['model']
            except Exception:
                self.svm = None

    @staticmethod
    def _font_candidates():
        return [
            '/usr/share/fonts/truetype/dejavu/DejaVuSansCondensed-Bold.ttf',
            '/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf',
            'C:/Windows/Fonts/arialbd.ttf',
            'C:/Windows/Fonts/arial.ttf',
        ]

    def _load_font(self, px):
        for p in self._font_candidates():
            if Path(p).exists():
                return ImageFont.truetype(p, px)
        return ImageFont.load_default()

    def _render_char(self, ch, px=58):
        canvas = Image.new('L', (72, 84), 255)
        d = ImageDraw.Draw(canvas)
        font = self._load_font(px)
        b = d.textbbox((0,0), ch, font=font)
        x = (72 - (b[2]-b[0]))//2 - b[0]
        y = (84 - (b[3]-b[1]))//2 - b[1]
        d.text((x,y), ch, font=font, fill=0)
        arr = np.array(canvas)
        return self._normalize_glyph(arr)

    def _build_templates(self):
        out = {}
        for ch in ALLOWED:
            variants = []
            for px in (52, 58, 64):
                variants.append(self._render_char(ch, px))
            out[ch] = variants
        return out

    def _normalize_glyph(self, img):
        if img.ndim == 3:
            img = cv2.cvtColor(img, cv2.COLOR_BGR2GRAY)
        _, bw = cv2.threshold(img, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
        ys, xs = np.where(bw > 0)
        if len(xs) == 0:
            return np.zeros((self.th, self.tw), np.uint8)
        crop = bw[ys.min():ys.max()+1, xs.min():xs.max()+1]
        scale = min((self.tw-4)/max(crop.shape[1],1), (self.th-4)/max(crop.shape[0],1))
        nw = max(1, int(crop.shape[1]*scale)); nh = max(1, int(crop.shape[0]*scale))
        r = cv2.resize(crop, (nw,nh), interpolation=cv2.INTER_AREA)
        dst = np.zeros((self.th,self.tw), np.uint8)
        x=(self.tw-nw)//2; y=(self.th-nh)//2
        dst[y:y+nh,x:x+nw] = r
        return dst

    def _binarize(self, crop):
        gray = cv2.cvtColor(crop, cv2.COLOR_BGR2GRAY) if crop.ndim == 3 else crop.copy()
        gray = cv2.resize(gray, None, fx=2, fy=2, interpolation=cv2.INTER_CUBIC)
        gray = cv2.GaussianBlur(gray, (3,3), 0)
        _, bw = cv2.threshold(gray, 0, 255, cv2.THRESH_BINARY_INV + cv2.THRESH_OTSU)
        # remove frame lines
        h,w=bw.shape
        bw[:max(1,h//25),:]=0; bw[-max(1,h//25):,:]=0
        bw[:,:max(1,w//50)]=0; bw[:,-max(1,w//50):]=0
        return bw

    def _segments(self, crop, plate_type):
        bw = self._binarize(crop)
        h,w = bw.shape
        if plate_type == 'type1a':
            # two rows; top is LDDD, bottom contains LL + region plus RUS marks.
            rows = [bw[:h//2, :], bw[h//2:, :]]
            segs=[]
            for ri,row in enumerate(rows):
                segs.extend(self._segments_single(row, expected=4 if ri==0 else 5))
            # keep 4 top + choose best 4/5 bottom based on geometry
            return segs[:9]
        return self._segments_single(bw, expected=9)

    def _segments_single(self, bw, expected=9):
        h,w=bw.shape
        n, labels, stats, _ = cv2.connectedComponentsWithStats(bw, 8)
        boxes=[]
        for i in range(1,n):
            x,y,cw,ch,area=stats[i]
            if area < max(8, h*w*0.0008): continue
            if ch < h*0.28 or ch > h*0.98: continue
            if cw < 2 or cw > w*0.30: continue
            boxes.append((x,y,cw,ch,area))
        # merge close fragments and drop tiny region/RUS decorations by height/area.
        boxes.sort(key=lambda b:b[0])
        if not boxes:
            return []
        med_h=np.median([b[3] for b in boxes])
        boxes=[b for b in boxes if b[3] >= med_h*0.70]
        # If too many, keep highest-area glyph-like components then restore x order.
        if len(boxes)>expected:
            boxes=sorted(boxes,key=lambda b:b[4],reverse=True)[:expected]
            boxes.sort(key=lambda b:b[0])
        return [bw[y:y+ch,x:x+cw] for x,y,cw,ch,_ in boxes]

    @staticmethod
    def _hog(g):
        g=cv2.resize(g,(32,48))
        hog=cv2.HOGDescriptor((32,48),(16,16),(8,8),(8,8),9)
        return hog.compute(g).reshape(1,-1)

    def _match(self, glyph):
        g = self._normalize_glyph(glyph)
        # Learned local SVM is the primary glyph classifier when available.
        if self.svm is not None:
            try:
                ch=str(self.svm.predict(self._hog(g))[0])
                scores=self.svm.decision_function(self._hog(g))
                margin=float(np.max(scores)) if np.ndim(scores)>0 else float(scores)
                conf=float(1/(1+np.exp(-margin)))
                return ch, max(0.0,min(1.0,conf))
            except Exception:
                pass
        # Deterministic template fallback keeps the solution operational offline.
        gf = g.astype(np.float32)/255.0
        best_ch='#'; best=-1.0
        for ch, vars in self.templates.items():
            for t in vars:
                tf=t.astype(np.float32)/255.0
                den=np.linalg.norm(gf)*np.linalg.norm(tf)
                s=float((gf*tf).sum()/den) if den>1e-6 else 0.0
                if s>best:
                    best=s; best_ch=ch
        return best_ch, max(0.0,min(1.0,(best-0.30)/0.55))

    def predict(self, crop, plate_type):
        glyphs=self._segments(crop, plate_type)
        if not glyphs:
            return '', 0.0
        chars=[]; conf=[]
        for g in glyphs:
            ch,c=self._match(g)
            chars.append(ch); conf.append(c)
        # type1a segmentation can include a RUS/flag fragment; let mask postprocessing reject extras.
        return ''.join(chars), float(np.mean(conf) if conf else 0.0)
